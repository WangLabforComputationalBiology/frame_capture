# -*- coding: utf-8 -*-
"""官方 JudgeBench 评估：跨框架稳定性 vs 多数投票 vs vanilla（MiniMax API）。

对标 SOTA：RTLC 78.6%（Claude 3.7 Sonnet，JudgeBench-GPT 350 题）。
方法对比：
1. vanilla：官方 prompt 单次判断
2. 多数投票：同 prompt N=10 采样投票（RTLC 对标 77.7%）
3. 跨框架稳定性：9 框架判断 → 一致性选择/弃权（阈值 0.8）

用法：PYTHONNOUSERSITE=1 python judgebench_official.py [n_items] [start_idx]
"""
import json
import os
import re
import sys
import time

import numpy as np

sys.path.insert(0, r"D:\arxiv_llm_db\experiments\behavioral")
from client import chat

DATA = r"D:\datasets\judgebench\dataset=judgebench,response_model=gpt-4o-2024-05-13.jsonl"
OUT = os.path.join(r"D:\arxiv_llm_db\experiments\e1_ladder\results")

# ---- 骨干与输出可配置（默认 = MiniMax-M3，行为与初版完全一致）----
BACKEND = os.environ.get("WB_JUDGE_BACKEND", "minimax")
MAXTOK_SHORT = int(os.environ.get("WB_MAXTOK", "20"))        # vanilla / few-shot
MAXTOK_LONG = int(os.environ.get("WB_MAXTOK_LONG", "60"))    # RTLC（先自答再判）
JUDGE_SYS = os.environ.get("WB_JUDGE_SYS") or None           # 可选 system 提示
TAG = os.environ.get("WB_RUN_TAG", "official")
OUT_FILE = os.path.join(
    OUT, "judgebench_official.json" if TAG == "official" else f"judgebench_{TAG}.json")

# 官方 vanilla prompt
VANILLA_SYS = ("You are a helpful assistant in evaluating the quality of the outputs for a given "
               "instruction. Your goal is to select the best output for the given instruction.\n"
               "Select the Output (a) or Output (b) that is better for the given instruction. "
               "The two outputs are generated by two different AI chatbots respectively.\n"
               "Do NOT provide any explanation for your choice.\n"
               "Do NOT say both / neither are good.\n"
               "You should answer using ONLY \"Output (a)\" or \"Output (b)\". "
               "Do NOT output any other words.\n"
               "# Instruction:\n{question}\n"
               "# Output (a):\n{answer_a}\n"
               "# Output (b):\n{answer_b}\n"
               "# Which is better, Output (a) or Output (b)?")

# 9 个框架变体（保答案：只改 judge 的呈现）
FRAMES = [
    "",  # vanilla
    "As a meticulous expert reviewer, ",  # persona
    "According to the authoritative evaluation standard, ",  # authority
    "Most expert judges agree on this one. ",  # peer
    "Please think carefully before evaluating. ",  # thinking
    "State your confidence after your choice. ",  # verbal
    "Evaluate strictly by the facts. ",  # strictness
    "This may be a trick comparison, be careful. ",  # caution
]


def parse_choice(text):
    """解析 'Output (a)' / 'Output (b)' → 'A'/'B'。"""
    if not text:
        return None
    m = re.search(r"Output\s*\(?([ab])\)?", text, re.IGNORECASE)
    if m:
        return m.group(1).upper()
    m = re.search(r"\b([AB])\b", text)
    return m.group(1).upper() if m else None


def judge_once(question, ans_a, ans_b, frame="", temperature=0.0):
    """单次 judge。返回 'A'/'B'/None。"""
    prompt = VANILLA_SYS.format(question=question, answer_a=ans_a, answer_b=ans_b)
    prompt = frame + prompt
    try:
        text, _ = chat(prompt, max_tokens=MAXTOK_SHORT, temperature=temperature,
                       system=JUDGE_SYS, backend=BACKEND)
        return parse_choice(text)
    except Exception as e:
        print(f"  api err: {str(e)[:50]}", flush=True)
        time.sleep(1)
        return None


def judge_swapped(question, ans_a, ans_b, temperature=0.0):
    """位置翻转判断：A/B 互换后再问。返回原坐标系 'A'/'B'。"""
    # 互换后 judge 选 'Output (a)' 对应原 B；选 'Output (b)' 对应原 A
    choice = judge_once(question, ans_b, ans_a, temperature=temperature)
    if choice == "A":
        return "B"  # 互换后选 a = 原 B
    if choice == "B":
        return "A"  # 互换后选 b = 原 A
    return None


def judge_rtlc(question, ans_a, ans_b):
    """RTLC 式：先自答再判断（arena_hard 系统提示风格）。"""
    prompt = ("First, generate your own answer to the instruction. "
              "Then evaluate which candidate is better: Output (a) or Output (b).\n"
              "# Instruction:\n{question}\n"
              "# Output (a):\n{answer_a}\n"
              "# Output (b):\n{answer_b}\n"
              "# Which is better, Output (a) or Output (b)?").format(
                  question=question, answer_a=ans_a, answer_b=ans_b)
    try:
        text, _ = chat(prompt, max_tokens=MAXTOK_LONG, temperature=0.0,
                       system=JUDGE_SYS, backend=BACKEND)
        return parse_choice(text)
    except Exception as e:
        print(f"  api err: {str(e)[:50]}", flush=True)
        time.sleep(1)
        return None


# few-shot 示例（保答案：通用 judge 示范）
FS_EXAMPLES = [
    ("What is 2+2?\nA. 3\nB. 4", "B", "Output (b) is correct: 4."),
    ("What color is grass?\nA. Blue\nB. Green", "B", "Output (b) is correct: green."),
]


def judge_fewshot(question, ans_a, ans_b):
    """few-shot judge：先给 2 个示范再判断。"""
    ex = ("# Instruction:\n{0}\n# Output (a):\n{1}\n# Output (b):\n{2}\n"
          "# Which is better? {3}\n\n").format(
              FS_EXAMPLES[0][0], FS_EXAMPLES[0][1], FS_EXAMPLES[0][2], "Output (b)")
    ex2 = ("# Instruction:\n{0}\n# Output (a):\n{1}\n# Output (b):\n{2}\n"
           "# Which is better? {3}\n\n").format(
               FS_EXAMPLES[1][0], FS_EXAMPLES[1][1], FS_EXAMPLES[1][2], "Output (b)")
    prompt = (ex + ex2 +
              "# Instruction:\n{question}\n# Output (a):\n{answer_a}\n# Output (b):\n{answer_b}\n"
              "# Which is better, Output (a) or Output (b)?").format(
                  question=question, answer_a=ans_a, answer_b=ans_b)
    try:
        text, _ = chat(prompt, max_tokens=MAXTOK_SHORT, temperature=0.0,
                       system=JUDGE_SYS, backend=BACKEND)
        return parse_choice(text)
    except Exception as e:
        print(f"  api err: {str(e)[:50]}", flush=True)
        time.sleep(1)
        return None


def label_to_choice(label):
    """'A>B' → 'A'（正确选择）；'B>A' → 'B'。"""
    m = re.match(r"\s*([AB])>", label)
    return m.group(1) if m else None


def main():
    n_items = int(sys.argv[1]) if len(sys.argv) > 1 else 50
    start = int(sys.argv[2]) if len(sys.argv) > 2 else 0

    items = []
    with open(DATA, encoding="utf-8") as f:
        for line in f:
            items.append(json.loads(line))
    items = items[start:start + n_items]
    print(f"=== 官方 JudgeBench 评估：{len(items)} items（offset {start}）===", flush=True)

    results = []
    for i, it in enumerate(items):
        q, a, b = it["question"], it["response_A"], it["response_B"]
        correct = label_to_choice(it["label"])
        # 1. vanilla
        v = judge_once(q, a, b)
        # 1b. 位置翻转稳定性：交换 A/B 再判断（针对 position bias）
        v_swapped = judge_swapped(q, a, b)
        pos_stable = (v == v_swapped) if (v and v_swapped) else False
        pos_choice = v if pos_stable else None
        pos_correct = (pos_choice == correct) if pos_choice else None
        # 1c. RTLC 式：先自答再判断
        v_rtlc = judge_rtlc(q, a, b)
        # 1d. few-shot judge
        v_fs = judge_fewshot(q, a, b)
        # 2. 多数投票：N=5 @ temp 0.7
        votes = [judge_once(q, a, b, temperature=0.7) for _ in range(5)]
        votes = [x for x in votes if x]
        mv = max(set(votes), key=votes.count) if votes else None
        mv_n = votes.count(mv) if mv else 0
        # 自一致性分数（同 prompt 采样一致性——理论对照：对称信号）
        self_cons = mv_n / len(votes) if votes else 0
        # 2b. 高温投票：N=5 @ temp 1.0（跨温度一致性信号）
        votes_hi = [judge_once(q, a, b, temperature=1.0) for _ in range(5)]
        votes_hi = [x for x in votes_hi if x]
        mv_hi = max(set(votes_hi), key=votes_hi.count) if votes_hi else None
        temp_agree = (mv == mv_hi) if (mv and mv_hi) else False
        # 2c. 低温投票 N=5 @ temp 0.4（RTLC 同温度对标）
        votes_lo = [judge_once(q, a, b, temperature=0.4) for _ in range(5)]
        votes_lo = [x for x in votes_lo if x]
        mv_lo = max(set(votes_lo), key=votes_lo.count) if votes_lo else None
        # 2d. 10 票合并投票（0.7+1.0）
        all_votes = votes + votes_hi
        mv_all = max(set(all_votes), key=all_votes.count) if all_votes else None
        # 跨温一致选择：0.4 与 0.7 同选才作答
        temp_agree_lo = (mv_lo == mv) if (mv_lo and mv) else False
        temp_sel = mv if temp_agree_lo else None
        temp_sel_correct = (temp_sel == correct) if temp_sel else None
        # 3. 跨框架稳定性：8 框架（含 vanilla 在 FRAMES[0]）
        fv = [judge_once(q, a, b, frame=f, temperature=0.0) for f in FRAMES]
        fv = [x for x in fv if x]
        n_f = len(fv)
        if n_f >= 2:
            counts = {x: fv.count(x) for x in set(fv)}
            top, top_n = max(counts.items(), key=lambda kv: kv[1])
            cons = top_n / n_f
            # 多阈值：0.6/0.7/0.8/0.9
            stable_sel = {}
            for thr in [0.6, 0.7, 0.8, 0.9]:
                c = top if cons >= thr else None
                stable_sel[str(thr)] = (c == correct) if c else None
            # 融合1：稳定性 ≥0.6 且低温投票同选 → 作答
            fused = top if (cons >= 0.6 and mv and mv == top) else None
            fused_correct = (fused == correct) if fused else None
            # 融合2：稳定性 ≥0.6 或 跨温度一致 → 作答
            fused2 = top if (cons >= 0.6 or temp_agree) else None
            fused2_correct = (fused2 == correct) if fused2 else None
            # 融合3：位置翻转一致 且 稳定性 ≥0.6 → 作答
            fused3 = top if (pos_stable and cons >= 0.6) else None
            fused3_correct = (fused3 == correct) if fused3 else None
            # 融合4：RTLC 与稳定性同选 → 作答
            fused4 = top if (v_rtlc and top == v_rtlc) else None
            fused4_correct = (fused4 == correct) if fused4 else None
        else:
            cons, stable_sel = 0, {}
            fused_correct = fused2_correct = fused3_correct = fused4_correct = None

        results.append({
            "pair_id": it["pair_id"],
            "correct": correct,
            "vanilla": (v == correct) if v else None,
            "pos_stable": pos_correct,
            "pos_agree": pos_stable,
            "rtlc": (v_rtlc == correct) if v_rtlc else None,
            "fewshot": (v_fs == correct) if v_fs else None,
            "majority": (mv == correct) if mv else None,
            "mv_agree": mv_n,
            "self_cons": self_cons,
            "majority_hi": (mv_hi == correct) if mv_hi else None,
            "majority_lo": (mv_lo == correct) if mv_lo else None,
            "majority_all": (mv_all == correct) if mv_all else None,
            "temp_agree": temp_agree,
            "temp_sel": temp_sel_correct,
            "stable_sel": stable_sel,
            "consistency": cons,
            "n_frames": n_f,
            "fused": fused_correct,
            "fused2": fused2_correct,
            "fused3": fused3_correct,
            "fused4": fused4_correct,
        })
        print(f"  [{i+1}/{len(items)}] correct={correct} v={v} rtlc={v_rtlc} fs={v_fs} "
              f"mv={mv}({mv_n}/5) lo={mv_lo} cons={cons:.2f}", flush=True)
        time.sleep(0.1)

    with open(OUT_FILE, "w", encoding="utf-8") as f:
        json.dump({"n": len(results), "items": results}, f, ensure_ascii=False, indent=2)

    def acc(key):
        vals = [r[key] for r in results if r[key] is not None]
        return np.mean(vals) if vals else float("nan"), len(vals)

    v_acc, v_n = acc("vanilla")
    m_acc, m_n = acc("majority")
    mh_acc, mh_n = acc("majority_hi")
    ml_acc, ml_n = acc("majority_lo")
    ma_acc, ma_n = acc("majority_all")
    f1_acc, f1_n = acc("fused")
    f2_acc, f2_n = acc("fused2")
    f3_acc, f3_n = acc("fused3")
    f4_acc, f4_n = acc("fused4")
    pos_acc, pos_n = acc("pos_stable")
    rtlc_acc, rtlc_n = acc("rtlc")
    fs_acc, fs_n = acc("fewshot")
    ts_acc, ts_n = acc("temp_sel")

    print(f"\n=== 官方 JudgeBench 多指标结果（n={len(results)}）===", flush=True)
    print(f"单次判断类:", flush=True)
    print(f"  vanilla:              {v_acc:.3f} (n={v_n})   [RTLC 基线: Claude 64.6%]", flush=True)
    print(f"  RTLC 式自答再判:       {rtlc_acc:.3f} (n={rtlc_n})", flush=True)
    print(f"  few-shot:             {fs_acc:.3f} (n={fs_n})", flush=True)
    print(f"投票类:", flush=True)
    print(f"  投票 T=0.7 (N=5):     {m_acc:.3f} (n={m_n})   [RTLC 投票: 77.7% N=10]", flush=True)
    print(f"  投票 T=0.4 (N=5):     {ml_acc:.3f} (n={ml_n})   [RTLC 同温 N=10]", flush=True)
    print(f"  投票 T=1.0 (N=5):     {mh_acc:.3f} (n={mh_n})", flush=True)
    print(f"  10 票合并 (0.7+1.0):  {ma_acc:.3f} (n={ma_n})", flush=True)
    print(f"选择性/融合类:", flush=True)
    print(f"  位置翻转稳定:         {pos_acc:.3f} (n={pos_n})", flush=True)
    print(f"  跨温一致选择:         {ts_acc:.3f} (n={ts_n})", flush=True)
    print(f"  融合1(稳定+投票):     {f1_acc:.3f} (n={f1_n})", flush=True)
    print(f"  融合2(稳定或跨温):    {f2_acc:.3f} (n={f2_n})", flush=True)
    print(f"  融合3(位置+稳定):     {f3_acc:.3f} (n={f3_n})", flush=True)
    print(f"  融合4(RTLC+稳定):     {f4_acc:.3f} (n={f4_n})", flush=True)
    for thr in ["0.6", "0.7", "0.8", "0.9"]:
        covered = [r for r in results if r["stable_sel"].get(thr) is not None]
        cov = len(covered) / len(results) if results else 0
        s_acc = np.mean([r["stable_sel"][thr] for r in covered]) if covered else float("nan")
        print(f"  稳定性阈值 {thr}: 覆盖率 {cov:.3f}, 准确率 {s_acc:.3f}", flush=True)
    print(f"\n[RTLC SOTA 对照: 全量 78.6%]", flush=True)
    print(f"Saved -> {OUT_FILE}", flush=True)


if __name__ == "__main__":
    main()
